@pytest.mark.parametrize("key", list(REFERENCE))
def test_values_unchanged_since_0_2_9(key):
    name, bw = key
    bandwidth, x, pdf, cdf, ppf = REFERENCE[key]
    kde = fs.Kde(SAMPLES[name](), bw=bw)
    x = np.array(x)
    np.testing.assert_allclose(kde.bandwidth, bandwidth, rtol=1e-12)
    np.testing.assert_allclose(kde.pdf(x), pdf, rtol=1e-12)
    np.testing.assert_allclose(kde.cdf(x), cdf, rtol=1e-12)
    np.testing.assert_allclose(kde.ppf(U), ppf, rtol=1e-12)
